import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../domain/entities/sales_report.dart';
import '../../domain/entities/sales_report_filter.dart';

class SalesReportPdfService {
  static final _currency = NumberFormat.currency(
    locale: 'en_PH',
    symbol: 'PHP ',
    decimalDigits: 2,
  );

  static String filename(SalesReportFilter filter) {
    final start = DateFormat('yyyyMMdd').format(filter.startDate);
    final end = DateFormat('yyyyMMdd').format(filter.endDate);
    return start == end
        ? 'xinpos-sales-report-$start.pdf'
        : 'xinpos-sales-report-$start-to-$end.pdf';
  }

  Future<List<int>> build({
    required SalesReport report,
    required SalesReportFilter filter,
  }) async {
    final document = pw.Document(
      title: 'xinPOS Sales Report',
      author: 'xinPOS',
      subject: 'Sales performance report',
    );

    final generatedAt = DateFormat('MMM d, yyyy • h:mm a')
        .format(DateTime.now());
    final dateRange = filter.startDate == filter.endDate
        ? DateFormat('MMMM d, yyyy').format(filter.startDate)
        : '${DateFormat('MMM d, yyyy').format(filter.startDate)} - ${DateFormat('MMM d, yyyy').format(filter.endDate)}';

    document.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        theme: pw.ThemeData.withFont(
          base: pw.Font.helvetica(),
          bold: pw.Font.helveticaBold(),
        ),
        footer: (context) => pw.Container(
          alignment: pw.Alignment.centerRight,
          margin: const pw.EdgeInsets.only(top: 16),
          child: pw.Text(
            'Generated by xinPOS • Page ${context.pageNumber} of ${context.pagesCount}',
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
          ),
        ),
        build: (context) => [
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text(
                    'xinPOS',
                    style: pw.TextStyle(
                      fontSize: 25,
                      fontWeight: pw.FontWeight.bold,
                    ),
                  ),
                  pw.SizedBox(height: 4),
                  pw.Text(
                    'SALES REPORT',
                    style: pw.TextStyle(
                      fontSize: 11,
                      letterSpacing: 2,
                      color: PdfColors.grey700,
                    ),
                  ),
                ],
              ),
              pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.end,
                children: [
                  pw.Text(dateRange, style: pw.TextStyle(fontSize: 10)),
                  pw.SizedBox(height: 4),
                  pw.Text(
                    'Generated $generatedAt',
                    style: const pw.TextStyle(
                      fontSize: 8,
                      color: PdfColors.grey600,
                    ),
                  ),
                ],
              ),
            ],
          ),
          pw.SizedBox(height: 20),
          _sectionTitle('OVERVIEW'),
          pw.Table(
            border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
            children: [
              _metricRow(
                'Total Revenue',
                _money(report.totalRevenueCentavos),
                'Transactions',
                report.transactionCount.toString(),
              ),
              _metricRow(
                'Items Sold',
                report.totalItemsSold.toString(),
                'Average Sale',
                _money(report.averageTransactionCentavos),
              ),
            ],
          ),
          pw.SizedBox(height: 20),
          _sectionTitle('DAILY SALES'),
          if (report.dailySales.isEmpty)
            _emptyText()
          else
            _table(
              ['Date', 'Transactions', 'Revenue'],
              report.dailySales
                  .map(
                    (item) => [
                      DateFormat('MMM d, yyyy').format(item.date),
                      item.transactionCount.toString(),
                      _money(item.revenueCentavos),
                    ],
                  )
                  .toList(),
            ),
          pw.SizedBox(height: 18),
          _sectionTitle('TOP-SELLING PRODUCTS'),
          if (report.topProducts.isEmpty)
            _emptyText()
          else
            _table(
              ['Product', 'Quantity Sold', 'Revenue'],
              report.topProducts
                  .map(
                    (item) => [
                      item.productName,
                      item.quantitySold.toString(),
                      _money(item.revenueCentavos),
                    ],
                  )
                  .toList(),
            ),
          pw.SizedBox(height: 18),
          _sectionTitle('PAYMENT METHODS'),
          if (report.paymentMethods.isEmpty)
            _emptyText()
          else
            _table(
              ['Payment Method', 'Transactions', 'Amount'],
              report.paymentMethods
                  .map(
                    (item) => [
                      item.method.toUpperCase(),
                      item.transactionCount.toString(),
                      _money(item.amountCentavos),
                    ],
                  )
                  .toList(),
            ),
          pw.SizedBox(height: 18),
          _sectionTitle('SALES BY CATEGORY'),
          if (report.categorySales.isEmpty)
            _emptyText()
          else
            _table(
              ['Category', 'Items Sold', 'Revenue'],
              report.categorySales
                  .map(
                    (item) => [
                      item.categoryName,
                      item.quantitySold.toString(),
                      _money(item.revenueCentavos),
                    ],
                  )
                  .toList(),
            ),
          pw.SizedBox(height: 20),
          pw.Divider(color: PdfColors.grey400),
          pw.Text(
            'This report includes completed transactions within the selected date range.',
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
          ),
        ],
      ),
    );

    return document.save();
  }

  static String _money(int centavos) => _currency.format(centavos / 100);

  static pw.Widget _sectionTitle(String title) {
    return pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 8),
      child: pw.Text(
        title,
        style: pw.TextStyle(
          fontSize: 10,
          fontWeight: pw.FontWeight.bold,
          color: PdfColors.blueGrey800,
          letterSpacing: 0.8,
        ),
      ),
    );
  }

  static pw.TableRow _metricRow(
    String firstLabel,
    String firstValue,
    String secondLabel,
    String secondValue,
  ) {
    return pw.TableRow(
      children: [
        _metricCell(firstLabel, firstValue),
        _metricCell(secondLabel, secondValue),
      ],
    );
  }

  static pw.Widget _metricCell(String label, String value) {
    return pw.Padding(
      padding: const pw.EdgeInsets.all(10),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text(
            label,
            style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey700),
          ),
          pw.SizedBox(height: 4),
          pw.Text(
            value,
            style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold),
          ),
        ],
      ),
    );
  }

  static pw.Widget _table(List<String> headers, List<List<String>> rows) {
    return pw.TableHelper.fromTextArray(
      headers: headers,
      data: rows,
      headerStyle: pw.TextStyle(
        fontSize: 8,
        fontWeight: pw.FontWeight.bold,
        color: PdfColors.white,
      ),
      headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
      cellStyle: const pw.TextStyle(fontSize: 8),
      cellPadding: const pw.EdgeInsets.symmetric(horizontal: 7, vertical: 6),
      border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
      oddRowDecoration: const pw.BoxDecoration(color: PdfColors.grey100),
    );
  }

  static pw.Widget _emptyText() {
    return pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 6),
      child: pw.Text(
        'No data for this period.',
        style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600),
      ),
    );
  }
}
